def _seg(box: tuple[int, int, int, int], conf: float | None, w: int = 1920, h: int = 1080) -> Segment:
    x1, y1, x2, y2 = box
    return Segment(box, (w, h), conf, np.full((y2 - y1, x2 - x1), 200, np.uint8))


